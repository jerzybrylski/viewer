known = set()
for path in (ROOT / 'drafts').rglob('*.jsonl'):
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.strip():
            row = json.loads(line)
            if row.get('translation', '').strip():
                known.add(row['id'])

rows_by_map = {map_id: [] for map_id in OUTPUTS}
unmapped = set()
for line in CANON.read_text(encoding='utf-8').splitlines():
    if not line.strip():
        continue
    row = json.loads(line)
    context = row.get('context') or {}
    map_id = context.get('map_id')
    source = ' '.join(row.get('source_text', '').strip().split())
    if (
        map_id not in OUTPUTS
        or row['id'] in known
        or row.get('category') != 'custom_dialogue'
        or context.get('source_kind') != 'map'
        or context.get('translation_policy') == 'keep_source_value'
        or not source
        or source.lstrip().startswith('/')
        or not any(char.isalpha() for char in source)
    ):
        continue
    translation = TRANSLATIONS.get(source)
    if translation is None:
        unmapped.add((map_id, context.get('event_id'), source))
        continue
    row['translation'] = translation
    rows_by_map[map_id].append(row)

if unmapped:
    raise SystemExit('Unmapped Map 61/25 strings: ' + repr(sorted(unmapped)))
for map_id, output in OUTPUTS.items():
    if output.exists():
        raise SystemExit(f'Refusing to overwrite {output}')
    rows = rows_by_map[map_id]
    if len(rows) != EXPECTED[map_id]:
        raise SystemExit(f'Map {map_id}: expected {EXPECTED[map_id]} natural dialogue lines, found {len(rows)}')
for map_id, output in OUTPUTS.items():
    rows = rows_by_map[map_id]
    output.write_text(
        ''.join(json.dumps(row, ensure_ascii=False, sort_keys=True) + '\n' for row in rows),
        encoding='utf-8',
        newline='\n',
    )
    print(f'Wrote {len(rows)} Map {map_id} dialogue lines across {len({r["context"]["event_id"] for r in rows})} events')
